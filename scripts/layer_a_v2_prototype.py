#!/usr/bin/env python3
"""Layer A v2 — a stream where the FUTURE VALUE depends on the current regime (DEC-521).

Why v2 exists: on the v1 reference, aggregates of the past (counts, sums, recency) beat the
latent truth at predicting forward value (R2 0.31 vs 0.09). A testbed in which the aggregate is
sufficient cannot fail the learned-encoder hypothesis, so it cannot support it either.

v2 changes ONE structural thing: value is generated by a **duration-dependent regime process**, so
*which state you are in now* — not your lifetime average — sets the forward value. Aggregates can
only infer the state indirectly; the latent truth knows it exactly. That is the headroom a learned
encoder is supposed to close.

Canonical nine-column schema, unchanged, so Layer B needs no code change (principle 4). Truth
exposes STATIC latents plus the regime at the anchor (`regime0 = state_at_anchor`), never realised
future paths.

This is a PROTOTYPE. It emits the same demo layout (`manifest.json`, stream, `reference_truth.json`)
so `measure_testbed_power.py` scores it with the pre-registered rule, unchanged.

    python3 scripts/layer_a_v2_prototype.py --out /tmp/opencode/layer_a_v2 --customers 2000
    python3 scripts/measure_testbed_power.py --demo /tmp/opencode/layer_a_v2
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import numpy as np

SECONDS_PER_DAY = 86400.0
EVENT_TYPES = ("view", "search", "purchase", "return", "email_send")
STATES = ("loyal", "at_risk", "dormant")
STATE_INTENSITY = np.array([1.0, 0.45, 0.08])
STATE_VALUE = np.array([1.0, 0.70, 0.40])
STATE_RETURN = np.array([0.6, 1.0, 1.4])


def _regime_path(rng, days: int, persistence: float) -> np.ndarray:
    """Duration-dependent regime process; returns a per-day state index.

    Durations are Weibull-ish (via exponential + shape), so the hazard rises with tenure —
    the property that makes the *time since last event* informative and an average uninformative.
    """
    state = 0
    out = np.empty(days, dtype=np.int8)
    t = 0
    scales = np.array([90.0 * persistence, 30.0, 45.0])
    while t < days:
        scale = scales[state]
        dur = int(np.clip(rng.weibull(1.6) * scale, 1, days))
        out[t : t + dur] = state
        t += dur
        if state == 0:
            state = 1
        elif state == 1:
            state = 2 if rng.random() < 0.65 else 0
        else:
            state = 0
    return out


def _runs(st: np.ndarray) -> list[list]:
    """[[state_name, n_days], ...] — run-length encoding of the realised regime path."""
    out: list[list] = []
    start = 0
    for i in range(1, len(st) + 1):
        if i == len(st) or st[i] != st[start]:
            out.append([STATES[int(st[start])], int(i - start)])
            start = i
    return out


def _churn_day(st: np.ndarray) -> int:
    """First day in `dormant`; the horizon if the customer never enters it."""
    idx = np.flatnonzero(st == 2)
    return int(idx[0]) if idx.size else int(len(st))


def build(out_dir: Path, n_customers: int, days: int, as_of_day: int, seed: int) -> dict:
    rng = np.random.default_rng(seed)
    start = datetime(2024, 1, 1, tzinfo=timezone.utc)
    day_epoch = np.array([(start + timedelta(days=d)).timestamp() for d in range(days)])

    base_rate = rng.lognormal(mean=-2.4, sigma=0.5, size=n_customers)
    value_scale = rng.lognormal(mean=3.4, sigma=0.6, size=n_customers)
    ret_prone = rng.beta(2.0, 20.0, size=n_customers)
    persistence = rng.uniform(0.4, 2.2, size=n_customers)
    timescale = rng.lognormal(mean=0.0, sigma=0.5, size=n_customers)
    price_sens = rng.beta(2.0, 2.0, size=n_customers)
    offer_opt = rng.integers(0, 4, size=n_customers)
    channel_pref = rng.choice(["email", "sms", "push"], size=n_customers)
    category_pref = rng.choice(["home", "apparel", "beauty", "footwear"], size=n_customers)
    touch_pref = rng.dirichlet(np.array([2.0, 1.0, 2.0]), size=n_customers)
    segment = rng.integers(1, 5, size=n_customers)
    signup_day = rng.integers(0, 30, size=n_customers)

    # seasonality: weekly + annual harmonics, derived here but data-visible through timestamps
    dow = np.array([(start + timedelta(days=d)).weekday() for d in range(days)])
    annual = 1.0 + 0.25 * np.sin(2 * np.pi * np.arange(days) / 365.0)
    weekly = 1.0 + 0.15 * (dow < 5)
    season = annual * weekly

    rows_key: list[np.ndarray] = []
    rows_ts: list[np.ndarray] = []
    rows_et: list[np.ndarray] = []
    rows_val: list[np.ndarray] = []
    rows_attr: list[str] = []
    states_at_anchor = np.empty(n_customers, dtype=np.int8)
    paths: list[np.ndarray] = []

    rho = 0.86
    for c in range(n_customers):
        key = f"v2{c:07d}"
        st = _regime_path(rng, days, float(persistence[c]))
        states_at_anchor[c] = st[as_of_day]
        paths.append(st)
        # intensity: rate x state x season x (1 + self-excitation)
        lam = base_rate[c] * STATE_INTENSITY[st] * season
        exc = np.zeros(days)
        acc = 0.0
        for d in range(days):
            exc[d] = acc
            acc = rho * acc + rng.poisson(lam[d]) if d < days - 1 else acc
        lam = lam * (1.0 + 0.35 * exc)

        n_buy = rng.poisson(lam)
        n_view = rng.poisson(lam * 3.0)
        n_search = rng.poisson(lam * 1.5)
        n_ret = rng.binomial(n_buy, np.clip(ret_prone[c] * STATE_RETURN[st], 0, 0.9))

        # value: lognormal whose MEAN depends on the state and the path (nonlinear interaction)
        buy_days = np.repeat(np.arange(days), n_buy)
        if buy_days.size:
            v_mu = (
                np.log(value_scale[c])
                + np.log(STATE_VALUE[st[buy_days]])
                + 0.30 * np.log1p(exc[buy_days])
                - 0.8 * price_sens[c] * np.log(1.05)
            )
            vals = rng.lognormal(mean=v_mu, sigma=0.45)
            jitter = rng.uniform(0, SECONDS_PER_DAY * 0.999, size=buy_days.size)
            rows_key.append(np.full(buy_days.size, key, dtype=object))
            rows_ts.append(day_epoch[buy_days] + jitter)
            rows_et.append(np.full(buy_days.size, "purchase", dtype=object))
            rows_val.append(vals)
            for v in vals:
                rows_attr.append(
                    json.dumps(
                        {
                            "value": round(float(v), 2),
                            "margin": round(float(v) * 0.31, 2),
                            "price": round(float(v), 2),
                            "qty": 1,
                            "discount": 0.0,
                            "product_id": f"p{int(rng.integers(0, 400)):03d}",
                            "category_code": str(category_pref[c]),
                            "brand": f"brand_{int(rng.integers(0, 10))}",
                            "touch": ["web", "store", "app"][int(np.argmax(touch_pref[c]))],
                        }
                    )
                )

        # views / searches: state-modulated, no value
        for et, n_arr in (("view", n_view), ("search", n_search)):
            d_idx = np.repeat(np.arange(days), n_arr)
            if d_idx.size:
                jitter = rng.uniform(0, SECONDS_PER_DAY * 0.999, size=d_idx.size)
                rows_key.append(np.full(d_idx.size, key, dtype=object))
                rows_ts.append(day_epoch[d_idx] + jitter)
                rows_et.append(np.full(d_idx.size, et, dtype=object))
                rows_val.append(np.zeros(d_idx.size))
                rows_attr.extend(
                    ['{"touch": "web", "category_code": "%s"}' % category_pref[c]] * d_idx.size
                )

        # returns
        ret_days = np.repeat(np.arange(days), n_ret)
        if ret_days.size:
            jitter = rng.uniform(0, SECONDS_PER_DAY * 0.999, size=ret_days.size)
            rows_key.append(np.full(ret_days.size, key, dtype=object))
            rows_ts.append(day_epoch[ret_days] + jitter)
            rows_et.append(np.full(ret_days.size, "return", dtype=object))
            rows_val.append(
                -rng.lognormal(mean=np.log(value_scale[c]) - 1.0, sigma=0.4, size=ret_days.size)
            )
            rows_attr.extend(['{"reason": "size"}'] * ret_days.size)

        # weekly randomized action (the known-effect arm)
        act_day = np.arange(signup_day[c] + 3, days, 7)
        if act_day.size:
            freq = rng.integers(0, 3, size=act_day.size)
            offer = rng.integers(0, 4, size=act_day.size)
            rows_key.append(np.full(act_day.size, key, dtype=object))
            rows_ts.append(
                day_epoch[act_day] + rng.uniform(0, SECONDS_PER_DAY * 0.999, act_day.size)
            )
            rows_et.append(np.full(act_day.size, "email_send", dtype=object))
            rows_val.append(np.zeros(act_day.size))
            for i, d in enumerate(act_day):
                rows_attr.append(
                    json.dumps(
                        {
                            "freq": int(freq[i]),
                            "offer": int(offer[i]),
                            "channel": str(channel_pref[c]),
                            "touch": "email",
                            "hour": 12,
                            "dow": int(dow[d]),
                        }
                    )
                )

        # signup event: P8 fixed — segment/tier/tenure are STREAM facts, not hidden columns
        rows_key.append(np.array([key], dtype=object))
        rows_ts.append(np.array([day_epoch[signup_day[c]]]))
        rows_et.append(np.array(["customer_signup"], dtype=object))
        rows_val.append(np.zeros(1))
        rows_attr.append(
            json.dumps(
                {
                    "segment": int(segment[c]),
                    "loyalty_tier": ["bronze", "silver", "gold", "platinum"][int(segment[c]) - 1],
                    "signup_ts": (start - timedelta(days=int(rng.integers(1, 400))))
                    .replace(tzinfo=None)
                    .isoformat(),
                    "region": "north",
                    "acquisition_channel": "referral",
                }
            )
        )

    import polars as pl

    df = pl.DataFrame(
        {
            "customer_key": np.concatenate(rows_key),
            "event_ts": np.concatenate(rows_ts),
            "event_type": np.concatenate(rows_et),
            "value": np.concatenate(rows_val),
            "source_table": "events",
            "event_attributes": rows_attr,
        }
    ).with_columns(
        pl.from_epoch(pl.col("event_ts").cast(pl.Int64), time_unit="s")
        .dt.strftime("%Y-%m-%dT%H:%M:%S%.6f")
        .alias("event_ts")
    )
    df = df.sort("event_ts")

    out_dir.mkdir(parents=True, exist_ok=True)
    stream = out_dir / "customer_event_stream.parquet"
    df.write_parquet(stream)

    truth = {
        "meta": {"generator": "layer_a_v2_prototype", "seed": seed, "days": days},
        "customers": [
            {
                "customer": f"v2{c:07d}",
                "x0": float(np.log1p(base_rate[c])),
                "h0": float(np.log(value_scale[c])),
                "d0": float(timescale[c]),
                "price_sensitivity": float(price_sens[c]),
                "return_proneness": float(ret_prone[c]),
                "segment": int(segment[c]),
                "offer_opt": int(offer_opt[c]),
                "channel_pref": str(channel_pref[c]),
                "category_pref": str(category_pref[c]),
                "regime0": STATES[int(states_at_anchor[c])],
                "regime_runs": _runs(paths[c]),
                "regime_switches": int((np.diff(paths[c]) != 0).sum()),
                "churn_day": float(_churn_day(paths[c])),
                "final_regime_days": int(_runs(paths[c])[-1][1]),
                # Bayes conditional mean of the forward outcome given the latent state at the
                # anchor. This is the oracle a sufficient statistic should match: the value
                # process is rate x state-intensity x value-scale x state-value.
                "bayes_fwd_value_90d": float(
                    90.0
                    * base_rate[c]
                    * STATE_INTENSITY[int(states_at_anchor[c])]
                    * value_scale[c]
                    * STATE_VALUE[int(states_at_anchor[c])]
                ),
                "bayes_fwd_count_90d": float(
                    90.0 * base_rate[c] * STATE_INTENSITY[int(states_at_anchor[c])]
                ),
                "touch_pref": [float(x) for x in touch_pref[c]],
            }
            for c in range(n_customers)
        ],
    }
    (out_dir / "reference_truth.json").write_text(json.dumps(truth, indent=1))
    (out_dir / "manifest.json").write_text(
        json.dumps(
            {
                "name": "layer_a_v2_prototype",
                "as_of": (start + timedelta(days=as_of_day)).strftime("%Y-%m-%d"),
                "window": {"start": start.strftime("%Y-%m-%d"), "days": days},
                "paths": {"B": {"stream": "customer_event_stream.parquet"}},
                "truth": "reference_truth.json",
            },
            indent=1,
        )
    )
    return {"events": int(df.height), "customers": n_customers, "stream": str(stream)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    ap.add_argument("--customers", type=int, default=2000)
    ap.add_argument("--days", type=int, default=540)
    ap.add_argument("--as-of-day", type=int, default=365)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args(argv)
    info = build(Path(a.out), a.customers, a.days, a.as_of_day, a.seed)
    print(json.dumps(info, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
